# Lane L6. Join every touch zone (K3 zones.tsv, 511 rows) to the key table the resolver selects for the
# page's display state, then walk the slot handler with the zone index known. Read-only; writes TSVs
# under ida\out\home-keytable\.
import sys, re, collections
sys.path.insert(0, '.')
from l6lib import *
from resolver import select
from walk import walk

OUT = R + "home-keytable/"
K3 = [l.rstrip("\n").split("\t") for l in open(R + "touch-screens/zones.tsv", encoding="utf-8") if not l.startswith("#")]
HDR = K3[0]; ROWS = [dict(zip(HDR, r)) for r in K3[1:]]

# ---- B3EA state -> pages (render tables 0x061C5A for A9F9=9, 0x0669E0 for A9F9=8/10), from l6 closure
#      (pages.py writes the evidence); parsed here from pages.tsv generated by pages.py
ST = collections.defaultdict(set)      # page -> set of (A9F9, B3EA)
STEV = {}                              # (page, A9F9, B3EA) -> evidence
for ln in open(OUT + "pages.tsv", encoding="utf-8"):
    if ln.startswith("#") or ln.startswith("page\t"): continue
    c = ln.rstrip("\n").split("\t")
    if c[1].startswith("A9F9="):
        m = re.match(r"A9F9=([0-9,]+) B3EA=(0x[0-9A-F]+)", c[1])
        if m:
            for a in m.group(1).split(','):
                ST[c[0]].add((int(a), int(m.group(2), 16)))
                STEV[(c[0], int(a), int(m.group(2), 16))] = c[3]

DIGPP = {0x270CA: 'digit', 0x27334: 'digit', 0x27648: 'digit', 0x279EA: 'digit+remap'}


def eff_key(T, v):
    if v < 0x8000: return 0x0A
    code = v & 0xFF; pp = DIGPP.get(T)
    if pp and code < 0x0A: return 0x00
    if pp == 'digit+remap' and code >= 0x0A: return code - 9
    return code


def guard_states(guard):
    """parse K3 guard atoms into resolver/walker state constraints"""
    s = {}
    for a in guard.split(' & '):
        a = a.strip()
        m = re.match(r"\[FF94C1\]==0x(\w+)$", a) or re.match(r"\[FF94C1\]==(\d)$", a)
        if m: s['C94C1'] = int(m.group(1), 16)
        m = re.match(r"\[FFB3EA\]==0x(\w+)$", a)
        if m: s['B3EA'] = int(m.group(1), 16)
        m = re.match(r"\[FFB3EA\]!=0x(\w+)$", a)
        if m: s.setdefault('B3EA_not', set()).add(int(m.group(1), 16))
        m = re.match(r"\[FFB3EA\] not in \{(.*)\}$", a)
        if m: s.setdefault('B3EA_not', set()).update(int(x, 16) for x in m.group(1).split(','))
    return s


def scenarios(page, guard, key=0x0A):
    """(label, resolver state, walker known) list for a page under a K3 guard"""
    g = guard_states(guard)
    base = {'key': key}
    if 'C94C1' in g: base['C94C1'] = g['C94C1']
    sc = []
    pg = int(page, 16)
    if page in ST:                                   # WIRES-X / mode-8/10 state machine pages
        for a9, b in sorted(ST[page]):
            if 'B3EA' in g and g['B3EA'] != b: continue
            if b in g.get('B3EA_not', ()): continue
            sc.append(("A9F9=%d B3EA=%#04x%s" % (a9, b, " [H5chain]" if STEV.get((page, a9, b)) == 'H5chain' else ""), dict(base, A9F9=a9, rec1=0), {'[FFB3EA]': b, '[FFA9F9]': a9, '[FFB39F].b1': 0, '[FFB39F].b2': 0, '[FFB39F].b3': 0, '[FFB420].b0': 0}))
        if 'B3EA' in g and not any(x[2]['[FFB3EA]'] == g['B3EA'] for x in sc):
            for a9 in sorted({a for a, _ in ST[page]}):
                sc.append(("A9F9=%d B3EA=%#04x(guard only)" % (a9, g['B3EA']), dict(base, A9F9=a9, rec1=0), {'[FFB3EA]': g['B3EA'], '[FFA9F9]': a9, '[FFB39F].b1': 0, '[FFB39F].b2': 0, '[FFB39F].b3': 0, '[FFB420].b0': 0}))
        if page[:2] != 'F1':
            return sc
    if page in ('F10D', 'F10F', 'F111'):
        b2 = 1 if page == 'F111' else 0     # render 0x00924C: BBE0.b2 -> 0x009398 (F111) else F10D/F10F
        sc.append(("A9F9=1 (render 0x004708 -> 0x9246), BBE0.2=%d, 89C5.0=1" % b2, dict(base, A9F9=1, rec1=0, C89C5_b0=1, BBE0_b2=b2), {'[FFA9F9]': 1, '[FFBBE0].b2': b2}))
        sc.append(("A9F9=1, BBE0.2=%d, 89C5.0=0" % b2, dict(base, A9F9=1, rec1=0, BBE0_b2=b2), {'[FFA9F9]': 1, '[FFBBE0].b2': b2}))
        return sc
    if page == 'F106':
        sc.append(("94C1=1 (render 0x004752 -> 0x8CBE) [primary]", dict(base, C94C1=1, rec1=0, rec5=1), {'[FF94C1]': 1}))
        sc.append(("94C1=1, rec+5==0", dict(base, C94C1=1, rec1=0, rec5=0), {'[FF94C1]': 1}))
        return sc
    if page == 'F107':
        sc.append(("94C0=1 & BBE0.1 (render 0x00475E-0x004772 -> 0x8E10), home, [89BB]==0", dict(base, C94C0=1, rec1=0), {'[FF94C0]': 1, '[FFBBE0].b1': 1, '[FF89BB]': 0}))
        return sc
    if page in ('F301',):
        sc.append(("screen 0x0D, BBF1.5=1", dict(base, rec1=0x0D, BBF1_b5=1), {'rec+0x1': 0x0D}))
        sc.append(("screen 0x0D, BBF1.5=0", dict(base, rec1=0x0D), {'rec+0x1': 0x0D}))
        return sc
    if page == 'F517':
        sc.append(("screen 0x9B (tab 0x782C slot 0x9B)", dict(base, rec1=0x9B), {'rec+0x1': 0x9B}))
        return sc
    if page == 'F004':
        sc.append(("screen 0xB3 (tab 0x782C slot 0xB3)", dict(base, rec1=0xB3), {'rec+0x1': 0xB3}))
        return sc
    if page in ('F3C3', 'F801', 'F10C', 'F10E', 'F110'):
        return [("no MAIN sender of %s (H5 opcode matrix; only the ladder compare holds the code)" % page, None, None)]
    if page == 'F112':
        # screen 0x0A pushed at 0x014BD8/0x014BDA when FF8EA9.7; render rec+1<0xC -> 0x004798 btst 8EA9.7 -> 0x0090B4 emits F112
        for r5 in ((0, 1) if 'C94C1' in base else (None,)):
            st = dict(base, rec1=0x0A)
            if r5 is not None: st['rec5'] = r5
            sc.append(("screen 0x0A (FF8EA9.7)%s" % ("" if r5 is None else ", rec+5=%d" % r5), st, {'rec+0x1': 0x0A}))
        return sc
    if page == 'F10B':
        # screen 0x0B pushed at 0x014BE8/0x014BEA when FF8EBD.7; render 0x0047A2 btst 8EBD.7 -> 0x008F88 emits F10B; also FF8EA0.4 on home
        sc.append(("screen 0x0B (FF8EBD.7) [primary]", dict(base, rec1=0x0B), {'rec+0x1': 0x0B}))
        for r5 in range(6):
            sc.append(("home + FF8EA0.4, rec+5=%d" % r5, dict(base, rec1=0, rec5=r5), {'rec+0x5': r5}))
        return sc
    if page in ('F100', 'F101', 'F103', 'F104', 'F105', 'F114', 'F115', 'FD00', 'F108'):
        for r5 in range(6):
            sc.append(("home, rec+5=%d" % r5, dict(base, rec1=0, rec5=r5), {'rec+0x5': r5}))
        return sc
    return [("page not modelled", 'K3', None)]


def slot_actions(h, known, idx):
    if h == SOFTKEY: return ["softkey_clear(3FFA0): no action"]
    K = dict(known); K['IDX'] = idx
    res = walk(h, K, maxpaths=120)
    out = []
    for p, end in res:
        acts = [a for a in p.acts if not a.startswith(('bset', 'bclr', 'bnot'))]
        cond = " & ".join(c for c in p.conds if c and '?' not in c)
        out.append(("[%s] " % cond if cond else "") + (" ; ".join(acts[:4]) if acts else "(no call)") + ("" if end in ('rts', 'end') else " <%s>" % end))
    return list(dict.fromkeys(out))


rows_out = []
stat = collections.Counter()
for r in ROWS:
    T = int(r['table'], 16); v = int(r['value'], 16); k3 = r['action']
    pages = r['pages'].replace(';', ',').split(',')
    guards = {}
    for part in r['page_guard'].split(' | '):
        if ':' in part:
            pp, g = part.split(':', 1)
            for p in pp.split(','): guards.setdefault(p.strip(), []).append(g.strip())
    slot = eff_key(T, v)
    idx = v if v < 0x8000 else 0
    trailer = r['note'].startswith('trailer')
    joins = []
    for page in pages:
        page = page.strip()
        if page == 'F200-F22C' or not page: continue
        for g in guards.get(page, ['-']):
            for label, st, kn in scenarios(page, g if g != '-' else '', slot):
                if st == 'K3':
                    joins.append((page, 'not re-modelled by L6; K3 join kept', '-', '-', ['K3: ' + k3[:300]])); continue
                if st is None:
                    joins.append((page, label, '-', '-', [label])); continue
                kt, why = select(st)
                if kt is None or isinstance(kt, str):
                    joins.append((page, label, '-', '-', ["key consumed before dispatch: %s %s" % (kt, why)])); continue
                h = be32(kt + 4 * slot)
                known = dict(kn); known['PAGE'] = int(page, 16)
                if 'C94C1' in st: known['[FF94C1]'] = st['C94C1']
                known.setdefault('[FF94C1]', st.get('C94C1', 0)); known.setdefault('[FF94C0]', st.get('C94C0', 0))
                known.setdefault('[FF8DDE]', 0)
                acts = slot_actions(h, known, idx)
                ktn = ("home#%d %06X" % (home_n(kt), kt)) if 0x1109C <= kt < 0x1208C else ("kt %06X" % kt)
                joins.append((page, label, ktn, "%06X" % h, acts))
    # classify
    was_pending = (k3 == 'unresolved')
    if trailer:
        status = 'trailer-unmatchable'
    elif not joins:
        status = 'not-modelled'
    else:
        hs = {j[3] for j in joins if j[3] != '-'}
        k3kept = all(j[1].startswith('not re-modelled') for j in joins)
        allsoft = all(a.startswith('softkey_clear') for j in joins for a in j[4])
        if k3kept:
            status = 'K3-join-kept'
        elif not hs:
            status = 'no-sender' if any('no MAIN sender' in a for j in joins for a in j[4]) else 'consumed'
        elif allsoft:
            status = 'resolved:no-op'
        elif len(hs) == 1:
            status = 'resolved:single-handler'
        else:
            status = 'resolved:state-dependent'
    stat[(was_pending, status)] += 1
    real = [j for j in joins if j[3] != '-']
    def rank(j):
        l = j[1]
        return (0 if '[primary]' in l else (1 if '[H5chain]' in l else 2), 0 if 'A9F9=9' in l else (1 if 'A9F9=10' in l else 2))
    prim = sorted(real, key=rank)[0] if real else None
    if prim:
        def score(x):
            tg_ = re.findall(r"-> ([0-9A-F]{6})", x)
            if tg_ and tg_[-1] != '03FFA0' and 'out of range' not in x: return 0
            if 'record' in x and 'softkey' not in x: return 1
            if re.search(r"jsr (?!03FFA0)[0-9A-F]{6}", x) and 'softkey' not in x: return 2
            if 'softkey' not in x: return 3
            return 4
        pa = sorted(prim[4], key=score)[0] if prim[4] else ''
        tg = re.findall(r"(?:-> |=|jsr |jmp )([0-9A-F]{6})", pa)
        fin = 'no-op (sub_3FFA0)' if ('softkey_clear' in pa and not tg) or (tg and tg[-1] == '03FFA0') else (tg[-1] if tg else ('store-only' if 'store' in pa else '-'))
        prim_cols = ["%s %s" % (prim[0], prim[1]), prim[2], prim[3], pa[:300], fin]
    else:
        prim_cols = ['-', '-', '-', '-', '-']
    jtxt = " || ".join("%s{%s} %s slot%d=%s => %s" % (p, l, kt, slot, h, " / ".join(a)[:600]) for p, l, kt, h, a in joins)
    rows_out.append([r['table'], r['zone'], r['x0'], r['y0'], r['x1'], r['y1'], r['value'], r['kind'], r['pages'],
                     'K3-pending' if was_pending else 'K3-joined', status, "0x%02X" % slot] + prim_cols + [jtxt or '-'])

hdr = "table\tzone\tx0\ty0\tx1\ty1\tvalue\tkind\tpages\tk3_status\tl6_status\tkey_A9ED(slot)\tprimary_state\tprimary_keytable\tprimary_slot_handler\tprimary_path\tprimary_target\tall_joins(page{state} keytable slot=handler => paths)"
open(OUT + "zones-resolved.tsv", "w", encoding="utf-8", newline="\n").write(
    "# Lane L6. All 511 K3 touch zones re-joined through the key-table resolver sub_1079E (0x01079E-0x011036). One row per zone.\n"
    "# For each page the zone is shown on, each display state (A9F9/B3EA/94C1/94C0/rec+5/screen) selects one key table; slot = 10 for buttons, the virtual key code otherwise.\n"
    "# paths: [conditions] actions, from walk.py with IDX=zone value, PAGE and the state known. idxN(tbl T[i]) = index helper (limit N) entry i. softkey_clear = sub_3FFA0 (no-op beep path).\n"
    + hdr + "\n" + "\n".join("\t".join(x) for x in rows_out) + "\n")
for k, n in sorted(stat.items(), key=lambda x: (not x[0][0], x[0][1])): print(k, n)
